function baseEntry(spec, fact, index, level) {
  const [work, statement] = fact;
  const number = spec.start + index;
  return {
    id: `rh-${{ 國小: 'e', 國中: 'j', 高中: 's' }[level]}-${number}`,
    level,
    zone: '修辭',
    cat: '譬喻',
    subcat: ASPECTS[index % 5],
    qformat: 'rh-pick',
    genre: '非韻文',
    textForm: '文言文',
    question: '待建立分級題目',
    options: [statement, '暫存一', '暫存二', '暫存三'],
    answer: statement,
    explain: statement,
    origin: '自編',
    citation: `${spec.author}《${spec.author === '莊子' ? '莊子・' : '楚辭・'}${work}》`,
    difficulty: LEVEL_DESIGN[level].difficulty,
    author: spec.author,
    work,
  };
}

for (const spec of SPECS) {
  for (const [level, design] of Object.entries(LEVEL_DESIGN)) {
    const entries = spec.facts.map((fact, index) => {
      const entry = baseEntry(spec, fact, index, level);
      return { ...entry, ...buildLevelFields(entry, level, index, fact[1]) };
    });
    fs.writeFileSync(`data/${spec.key}-${design.suffix}.json`, `${JSON.stringify(entries, null, 2)}\n`);
  }
}

